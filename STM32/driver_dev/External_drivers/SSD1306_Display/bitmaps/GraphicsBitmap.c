/*
 * Bitmap Format
 * -------------
 * Bitmaps are stored as 1-bit-per-pixel (1 BPP) monochrome images.
 *
 * - Each bit represents one pixel:
 *       1 = pixel ON
 *       0 = pixel OFF
 *
 * - Bitmap data is stored in ROW-MAJOR order:
 *       Rows are stored from top to bottom.
 *       Within each row, pixels are stored from left to right.
 *
 * - Pixels are stored MSB-FIRST within each byte:
 *       Bit 7 = leftmost pixel
 *       Bit 0 = rightmost pixel
 *
 * - Each row is padded to a whole number of bytes.
 *
 *   bytes_per_row = (width + 7) / 8
 *
 * Example: 8x2 bitmap
 *
 *   Pixels:       00111100
 *                 01000010
 *
 *   Data:         0x3C, 0x42
 *
 * Example: 10-pixel-wide row
 *
 *   Pixels:       0011110011
 *   Bytes:        00111100 11000000
 *                 ^^^^^^^^ ^^^^^^
 *                  8 bits   2 pixels + 6 padding bits
 *
 * Therefore:
 *
 *   bitmap_size = bytes_per_row * height
 *
 */

