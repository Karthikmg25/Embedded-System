#include <opencv2/opencv.hpp>
#include <cstdio>
#include <iostream>
#include <string>
#include <cctype>

int main()
{
    std::cout << "Program started\n";

    // Open the camera.
    cv::VideoCapture camera(0);

    if (!camera.isOpened())
    {
        std::cout << "Failed to open camera\n";
        return 1;
    }

    std::cout << "Camera opened successfully\n";

    cv::Mat frame;

    while (true)
    {
        // Capture a frame from the camera.
        camera >> frame;

        if (frame.empty())
        {
            std::cout << "Failed to capture frame\n";
            break;
        }

        // Display the camera feed.
        cv::imshow("Camera", frame);

        // Wait for a key press.
        int key = cv::waitKey(1);

        // Exit when 'q' is pressed.
        if (key == 'q')
        {
            break;
        }

        // When 'c' is pressed, capture the audio and frame and analyze 
        // whisper and VLM runs when capture occurs.
        if (key == 'c')
        {
            std::cout << "Starting voice input...\n";
            std::cout<< " \n\n press R to start recording and S to stop";

            FILE *whisper = _popen("C:\\Users\\hp\\Desktop\\VLM\\VLM_camera\\voice_speech.exe", "r");
            if(whisper == nullptr)
            {
                std::cout<<"Failed to start recording";
                continue;
            }
            // Buffer for reading one line at a time.
            char line_buffer[256];

            // Store the prompt generated by whisper in a string
            std::string prompt;

            // Read output from whisper
            while (fgets(line_buffer, sizeof(line_buffer), whisper) != nullptr)
            {
                std::string line = line_buffer;

                // Ignore log lines.
                if (line.find(" I ") == std::string::npos &&
                    line.find(" W ") == std::string::npos)
                {
                    prompt += line;
                }
            }

            // Close whisper after audio input and prompt generation
            _pclose(whisper);

            // Remove leading whitespace
            while (!prompt.empty() &&
            std::isspace(static_cast<unsigned char>(prompt.front())))// checks if first character is whitespace
            {
                // remove first character
                prompt.erase(prompt.begin());
            }

            // Remove trailing whitespace
            while (!prompt.empty() &&
            std::isspace(static_cast<unsigned char>(prompt.back())))
            {
                //removes last character
                prompt.pop_back();
            }

           std::cout << "\n\nGenerated prompt is : [" << prompt << "]\n";

            // Save the current frame.
            if (cv::imwrite("capture.jpg", frame))
            {
                std::cout << "\nImage captured successfully\n";
            }
            else
            {
                std::cout << "Failed to save image\n";
                continue;
            }

            // Command to run the VLM.
               
                std::string command =
                "C:/Users/hp/Desktop/VLM/llama.cpp-current/build/bin/llama-mtmd-cli.exe "
                "-m \"F:/AI Models/VLM/Qwen2.5-VL-3B-Instruct-Q4_K_M.gguf\" "
                "--mmproj \"F:/AI Models/VLM/mmproj-Qwen2.5-VL-3B-Instruct-f16.gguf\" "
                "--image \"C:/Users/hp/Desktop/VLM/VLM_camera/capture.jpg\" "
                 "-p \"" + prompt + "\"";

                // debug command
                std::cout << "\nDEBUG COMMAND:\n";
                std::cout << command << "\n\n";
                // Launch VLM after saving the image //
                
            // Start VLM process and create pipe.
            FILE *pipe = _popen(command.c_str(), "r");

            if (pipe == nullptr)
            {
                std::cout << "Failed to start VLM\n";
                continue;
            }

            // Buffer for reading one line at a time.
            char buffer[256];

            // Store the filtered VLM response.
            std::string output;

            // Read output from VLM.
            while (fgets(buffer, sizeof(buffer), pipe) != nullptr)
            {
                std::string line = buffer;

                // Remove newline characters
                //line.erase(std::remove(line.begin(), line.end(), '\n'), line.end());
                //line.erase(std::remove(line.begin(), line.end(), '\r'), line.end());

                // Ignore llama.cpp log lines.
                if (line.find(" I ") == std::string::npos &&
                    line.find(" W ") == std::string::npos)
                {
                    output += line;
                }
            }

            // Close pipe and wait for VLM process to finish.
            _pclose(pipe);

            // Display VLM description.
            std::cout << "\n----- VLM DESCRIPTION -----\n";
            std::cout << output << "\n";

            //replace all newline characters with space in the output with space
            auto it = output.begin();

            for(auto i = it;i!=output.end();i++)
            {
                if(*i == '\n' || *i == '\r')
                {
                    *i = ' ';
                }
                
            }

            //run the piper program to convert VLM responce to voice
            std::string piper_cmnd = "piper_player.exe \""+ output + "\"";

            //debug piper_command
            std::cout<<"\n\nPiper command: "<<piper_cmnd;

            //run command
            system(piper_cmnd.c_str());

        }
    }

    // Release camera resources.
    camera.release();

    // Close OpenCV windows.
    cv::destroyAllWindows();

    return 0;
}